export function translate(language, key, params = {}) {
  const text = dictionaries[language]?.[key] ?? dictionaries.ky[key] ?? key ?? "";
  return String(text).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
export function localizedField(entity, field, language) {
  const translated = entity?.translations?.[language]?.[field] ?? entity?.[field + "Translations"]?.[language];
  if (typeof translated === "string" && translated.trim()) return translated;
  const original = entity?.[field];
  if (typeof original === "string") return original;
  if (original && typeof original === "object") return original[language] || original.ky || original.ru || original.en || original.tr || "";
  return "";
}
export function optionValueLabel(option, value, language) {
  const labels = option?.translations?.[language]?.values;
  const translated = Array.isArray(labels) ? labels.find(entry => entry.value === value)?.label : labels?.[value];
  return typeof translated === "string" && translated.trim() ? translated : option?.valueTranslations?.[value]?.[language] || value;
}
export function optionSummary(item, language) {
  return Object.entries(item.selectedOptions || {}).map(([key,value]) => {
    const option = item.productSnapshot?.options?.find(candidate => candidate.name === key);
    return (option ? localizedField(option, "name", language) : key) + ": " + (option ? optionValueLabel(option,value,language) : value);
  }).join(" · ");
}
